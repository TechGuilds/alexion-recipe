import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const read = relative => readFileSync(new URL(relative, import.meta.url), 'utf8').replace(/\r\n/g, '\n');

test('Sitecore Code Migration is rendering-led, stateful and does not assume the next phase', () => {
  const profile = read('../references/profiles/sitecore/pipeline/code-migration.md');
  const frontend = read('../../../agents/frontend-developer.md');
  const orchestrator = read('../../../agents/orchestrator.md');
  const state = read('../references/workflow-state.md');
  const catalog = JSON.parse(read('../assets/profiles/sitecore/phase-catalog.json'));
  assert.match(profile, /approved workflow.*evidence-backed dependencies/i);
  assert.match(profile, /rendering entities.*not React AST candidates/i);
  assert.match(profile, /mapping\.json/);
  assert.match(profile, /entityId/);
  assert.match(profile, /current hashes/);
  assert.match(profile, /parent\/frontier and route-host readiness/);
  assert.match(profile, /create one `prepare-task-packet\.mjs` handoff before dispatch/i);
  assert.match(profile, /stable identity\/source join.*page-aware route\/fixture.*code-analysis report/s);
  assert.match(profile, /per rendering.*route\/feature batch/s);
  assert.match(profile, /all mapped renderings meet acceptance/);
  assert.match(profile, /actual target route\/browser render/);
  assert.match(profile, /mock-layout-scaffold.*shared-styles-shell.*preview-foundation.*page-aware rendering work/s);
  assert.match(profile, /task-owned preview-input manifest/i);
  assert.match(profile, /task consumes that manifest instead of scanning repositories, fixtures or stale indexes/i);
  assert.match(frontend, /do not create a temporary capture harness, probe route aliases, or rerun broad source\/fixture discovery/i);
  assert.match(profile, /Omit already equivalent scaffold\/style work independently, while retaining the readiness task/i);
  assert.match(profile, /JSS targets require a separately verified target loader\/integration; the scaffold is SitecoreAI-specific/i);
  assert.match(profile, /Do not repeat broad GraphQL queries or impose one target's mock integration on another framework/i);
  assert.match(profile, /do not rank any route-dependent rendering task.*`preview-foundation` evidence/i);
  assert.match(profile, /source-declared, non-jQuery package/i);
  assert.match(profile, /current source and target manifests/i);
  assert.match(profile, /package-manager health\/type\/build check/i);
  assert.match(frontend, /source-declared, non-jQuery package/i);
  assert.match(frontend, /existing package manager/i);
  assert.match(profile, /local checkpoint commit containing exactly this task's changed paths/i);
  assert.match(profile, /tester's read-only diff-on-failure diagnosis before redo/i);
  assert.match(profile, /canceled, empty or nonterminal worker return.*incomplete attempt/i);
  assert.match(profile, /Do not mark it done, request human verification, create a checkpoint commit or dispatch another task/i);
  assert.match(profile, /`verification` decisions against each item's exact selected result\/evidence hashes/i);
  assert.match(profile, /Do not report the phase as fully verified while any included rendering remains unsigned/i);
  assert.match(profile, /failed, blocked, explicitly skipped, unresolved and excluded/);
  assert.match(profile, /rendering definition, source implementation path\(s\), routes and data\/resolver facts/i);
  assert.match(profile, /one aggregate coverage-audit task for the tester/i);
  assert.ok(catalog.goldenExamples.find(phase => phase.key === 'code-migration').tasks.some(task => /audit per-rendering coverage/i.test(task)));
  const codeMigration = catalog.goldenExamples.find(phase => phase.key === 'code-migration');
  assert.ok(codeMigration.taskPatterns.some(pattern => /mandatory preview-foundation/i.test(pattern)));
  assert.ok(codeMigration.tasks.some(task => /mandatory preview-foundation/i.test(task)));
  assert.match(frontend, /browser.*unresolved.*not.*success/i);
  assert.match(frontend, /Read the dispatch task packet first/i);
  assert.match(frontend, /do not re-read global workflow state, schemas, skill source or unrelated Discovery reports/i);
  assert.match(orchestrator, /include that request path in the\s*worker dispatch/i);
  assert.match(orchestrator, /run `next-work\.mjs` once.*prepare-task-packet\.mjs/s);
  assert.doesNotMatch(profile, /Ask to continue to Content Migration/);
  assert.match(state, /do not assume Code Migration precedes Content Migration/i);
});


test('preview readiness is required for new and adopted apps before rendering work', () => {
  const profile = read('../references/profiles/sitecore/pipeline/code-migration.md');
  const discovery = read('../references/profiles/sitecore/pipeline/discovery.md');
  const frontend = read('../../../agents/frontend-developer.md');
  assert.match(profile, /mandatory.*`preview-foundation`.*new and adopted apps/i);
  assert.match(discovery, /`preview-foundation`.*frontend-developer.*dependency/s);
  assert.match(profile, /preview-readiness\.md/);
  assert.match(frontend, /preview-readiness\.md/);
  const readiness = read('../references/profiles/sitecore/pipeline/preview-readiness.md');
  assert.match(readiness, /coordinator.*launch.*before dispatch/i);
  assert.match(readiness, /preview_list.*preview_run/s);
  assert.match(readiness, /preview_logs/);
  assert.match(readiness, /probe-render\.mjs/);
  assert.match(readiness, /browser.*agreed route/s);
  assert.match(readiness, /restart.*resume/i);
  assert.match(readiness, /blocked.*dependent rendering work/s);
  assert.match(readiness, /Technical report/);
});
